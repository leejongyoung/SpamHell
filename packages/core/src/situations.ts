export type SituationId = (typeof SITUATIONS)[number]['id'];

export const SITUATION_IDS = SITUATIONS.map((situation) => situation.id) as readonly SituationId[];

export function isSituationId(value: string): value is SituationId {
  return (SITUATION_IDS as readonly string[]).includes(value);
}

export function getSituation(id: SituationId): Situation {
  const situation = SITUATIONS.find((candidate) => candidate.id === id);
  if (!situation) {
    throw new TypeError(`Unknown situation: ${String(id)} (expected one of ${SITUATION_IDS.join(', ')})`);
  }
  return situation;
}

export interface ReplyLineOptions {
  seed?: number | string;
  rng?: Rng;
}

/** 상황에 맞는 답장 문구 하나(평문)를 고른다. 웹 작성기처럼 직접 고쳐 쓰고 싶을 때 쓴다. */
export function getReplyLine(id: SituationId, options: ReplyLineOptions = {}): string {
  return pick(resolveRng(options), getSituation(id).replies);
}

export interface ReplyOptions extends Omit<SpamOptions, 'rng'> {
  rng?: Rng;
  /** 변환 방식. 기본은 스팸체. */
  mode?: 'spam' | 'korean';
}

/**
 * 상황에 맞는 답장을 골라 바로 변환한다. 같은 시드와 상황이면 어디서나 같은 결과다.
 * 답장 선택과 변환이 하나의 난수열을 이어서 쓴다.
 */
export function getReply(id: SituationId, options: ReplyOptions = {}): string {
  const { mode = 'spam', ...spamOptions } = options;
  if (mode !== 'spam' && mode !== 'korean') {
    throw new TypeError(`mode must be 'spam' or 'korean', got ${String(mode)}`);
  }
  const rng = resolveRng(options);
  const line = pick(rng, getSituation(id).replies);
  return mode === 'korean' ? toKorean(line, { rng }) : toSpam(line, { ...spamOptions, rng });
}

