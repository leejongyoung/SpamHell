/**
 * 받은 문자에 가장 잘 맞는 상황을 고른다. 일치한 키워드 수가 가장 많은 상황이고, 동점이면 SITUATIONS 순서가 앞선 쪽이다.
 * 일치하는 키워드가 하나도 없으면 `null`. 난수를 쓰지 않으므로 언제나 같은 결과다.
 */
export function matchSituation(text: string): SituationId | null {
  const haystack = text.toLowerCase();
  let best: SituationId | null = null;
  let bestScore = 0;
  for (const id of SITUATION_IDS) {
    let score = 0;
    for (const keyword of SITUATION_KEYWORDS[id]) {
      if (haystack.includes(keyword)) score += 1;
    }
    if (score > bestScore) {
      best = id;
      bestScore = score;
    }
  }
  return best;
}
